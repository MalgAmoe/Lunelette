"""Generate property runs; no regex implementation code is copied.
Requires the existing regex 2026.9.29 (Unicode 18.0.0) environment.
Usage: python generate_unicode.py /path/to/src/tokenizer_unicode.h
"""
import sys
import regex
assert regex.__version__ == '2026.9.29'
props = [regex.compile(r'\A\p{%s}\Z' % p) for p in
         ['L', 'Lu', 'Lt', 'Lm', 'Lo', 'M', 'Ll', 'N', 'White_Space']]
runs = []
start = 0
last = None
for cp in range(0x110000):
    mask = sum(1 << i for i, pat in enumerate(props) if pat.fullmatch(chr(cp)))
    if mask != last:
        if last is not None and last:
            runs.append((start, cp - 1, last))
        start, last = cp, mask
if last:
    runs.append((start, 0x10ffff, last))
with open(sys.argv[1], 'w') as f:
    f.write('/* Generated by tests/tokenizer_generate_unicode.py.\n'
            ' * regex 2026.9.29, Unicode 18.0.0; property data only.\n'
            ' * See tokenizer_unicode_LICENSE.txt for source package notices.\n'
            ' * Masks: L, Lu, Lt, Lm, Lo, M, Ll, N, White_Space.\n'
            ' * Self-contained: no runtime regex/locale dependency. */\n'
            '#ifndef LUNELETTE_TOKENIZER_UNICODE_H\n'
            '#define LUNELETTE_TOKENIZER_UNICODE_H\n'
            'static const struct { unsigned first, last, mask; } tk_unicode[] = {\n')
    for a, b, m in runs:
        f.write(f'    {{0x{a:x}, 0x{b:x}, {m}}},\n')
    f.write('};\n#endif\n')
print(len(runs), 'runs')
